import assert from 'node:assert/strict';
import { Dreaming, parseMemories, profileWithDream, notePath, DREAM_START, DREAM_END } from '../src/dream.js';
import { DEFAULTS, deepMerge, journalPath, dayKeyToday } from '../src/constants.js';
const sources = new Map([['S1',{kind:'user'}],['S2',{kind:'ai'}]]);
const answer = (memories) => JSON.stringify({memories});
const fact = {text:'偏好中文回复',kind:'preference',sources:['S1']};
assert.equal(parseMemories(answer([fact,fact]),sources).length,1);
assert.throws(()=>parseMemories(answer([{...fact,sources:['unknown']}]),sources),/来源/);
assert.throws(()=>parseMemories(answer([{...fact,sources:['S2']}]),sources),/AI/);
assert.throws(()=>parseMemories(answer([{...fact,text:'<!-- break -->'}]),sources));
assert.throws(()=>parseMemories('not json',sources));
assert.equal(parseMemories(answer([{...fact,kind:'lesson',sources:['S2']}]),sources).length,1);
for (const path of ['../memory.md','/tmp/m.md','C:/m.md','a/../m.md']) assert.throws(()=>notePath(path));
let profile = '用户原本写的\n\n## 最近\n原来的内容\n';
const merged = profileWithDream(profile,'记忆一');
assert.equal(profileWithDream(merged,'记忆一'),merged);
const replaced = profileWithDream(merged,'记忆二');
assert.ok(replaced.startsWith(profile.trimEnd())); assert.ok(!replaced.includes('记忆一'));
assert.throws(()=>profileWithDream(profile+DREAM_START,'new'));
assert.throws(()=>profileWithDream(DREAM_END+DREAM_START,'new'));
const files = new Map(), notices = [];
const settings = deepMerge(DEFAULTS,{});
const vault = {getAbstractFileByPath:(path)=>files.has(path)?{path}:null,read:async(f)=>files.get(f.path),modify:async(f,t)=>files.set(f.path,t),process:async(f,fn)=>files.set(f.path,fn(files.get(f.path))),create:async(p,t)=>{files.set(p,t);return {path:p}},createFolder:async(p)=>files.set(p,'')};
const p = { settings,jobs:{},app:{vault,plugins:{getPlugin:()=>({companion:{cfg:{profilePath:'陪伴.md'}}})},workspace:{openLinkText:async()=>{}}},saveSettings:async()=>{},notice:(t)=>notices.push(t)};
files.set('陪伴.md',profile);
files.set(journalPath(p.app,settings,dayKeyToday(settings)), '- TODO 用户日志：以后请用中文回复\n  - 💬 AI 记录：构建完成');
let calls=0;
const dream = new Dreaming(p,async()=>{calls++;files.set(settings.dream.path,'# 手工维护\n手动补的记忆');return answer([fact]);});
settings.dream.syncProfile=true;
const evidence = await dream.collect();
assert.equal(evidence.get('S1').kind,'user'); assert.equal(evidence.get('S2').kind,'ai');
assert.ok(!evidence.get('S1').text.includes('构建完成'));
await dream.run();
const memory = files.get(settings.dream.path);
assert.ok(memory.includes('手动补的记忆')); assert.ok(memory.includes('[[日记/')); assert.ok(memory.includes('偏好中文回复'));
assert.ok(files.get('陪伴.md').includes('用户原本写的')); assert.ok(files.get('陪伴.md').includes('偏好中文回复'));
await dream.run(); assert.equal(calls,1); assert.equal(files.get(settings.dream.path),memory);
const exported = await dream.exportMemory(); assert.equal(files.get(exported),memory);
settings.dream.enabled=true;
await dream.tick(); assert.equal(calls,1);
settings.dream.fingerprint='changed';
dream.model=async()=> 'invalid';
await dream.run(); assert.equal(files.get(settings.dream.path),memory); assert.ok(settings.dream.lastError);
settings.dream.lastRun=0; settings.dream.lastAttempt=Date.now();
await dream.tick(); assert.equal(files.get(settings.dream.path),memory);
dream.model=async()=>{await new Promise(r=>setTimeout(r,20));calls++;return answer([])};
await Promise.all([dream.run(),dream.run()]); assert.equal(calls,2);
console.log('PASS dreaming: evidence validation, AI/user separation, manual edits, profile preservation, idempotency, export, retry and concurrency');
