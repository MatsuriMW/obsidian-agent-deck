// Agent Deck — interface language.
//
// Obsidian stores the app language in localStorage under "language". Chinese
// users keep the original strings; every other locale gets the English table.
// Journal text, status keywords and model prompts are data, not UI, so they are
// deliberately not routed through here.

function detect() {
  try {
    if (typeof localStorage !== "undefined") {
      const l = localStorage.getItem("language");
      if (l) return l;
    }
  } catch { /* no storage */ }
  try {
    if (typeof navigator !== "undefined" && navigator.language) return navigator.language;
  } catch { /* no navigator */ }
  return "en";
}

